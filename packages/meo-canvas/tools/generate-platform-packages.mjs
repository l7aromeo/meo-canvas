// The two places a target is named that are not `TARGETS`, written from it.
//
// A target used to be declared in three places: `TARGETS` here in the tools,
// `optionalDependencies` in `package.json` (what an install *fetches*), and
// `PLATFORM_PACKAGES` in `src/addon.ts` (what a process *resolves*). A test
// asserted the three agreed, which caught drift but did not prevent it —
// adding two targets meant editing three files and being told about the two
// you forgot. **Generation removes the possibility rather than reporting it**,
// and the drift check replaces that assertion rather than joining it: a
// generated file plus an equality test between it and its source is one
// mechanism written twice, and a reader cannot tell which is authoritative.
//
// # Why a committed file and not an import
//
// `src/addon.ts` ships inside `dist/`; `tools/` does not ship. The runtime
// cannot import the build-time list, so the list has to arrive in the package
// as source. That is the same constraint `src/generated/doc-examples.ts`
// answers, and this follows it: generate, commit, and fail a gate on a
// difference.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { TARGETS } from './stage-platform-package.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const PACKAGE = resolve(HERE, '../package.json')
const GENERATED = resolve(HERE, '../src/generated/platform-packages.ts')

/**
 * The package a target's binary ships in: a scope named for the main package,
 * with the target suffix as the package name.
 *
 * **Scoped, and npm's spam heuristic is why.** The unscoped
 * `meo-canvas-<suffix>` names were refused with `E403 Package name triggered
 * spam detection` on 5 September 2026 -- two isolated publishes, nineteen
 * hours after the previous attempt, two different names, on the account that
 * had published four packages of exactly that shape the day before. So it was
 * neither a burst nor those particular names, and spacing the attempts could
 * not have helped. A scope is a namespace with an owner, which is what
 * name-squatting detection has far less to fire on, and it is what every
 * comparable project already ships: `@esbuild/darwin-arm64`,
 * `@rollup/rollup-darwin-arm64`, `@swc/core-darwin-arm64`.
 *
 * **The main package stays unscoped**, so `npm install meo-canvas` is
 * unchanged and v9's lineage continues at 10.x. Only the binaries move, and
 * `optionalDependencies` resolves them from the same registry by name, so no
 * consumer needs an `.npmrc` or a credential.
 *
 * `npm pack` names a scoped tarball `<scope>-<name>-<version>.tgz`, so this
 * produces exactly the filenames the unscoped scheme did -- which is why
 * `release.yml`'s prefix glob needs no change.
 */
function packageName(main, suffix) {
  // A scoped main package would give `@@scope/name/suffix`, which is not a
  // name npm accepts. Refuse rather than emit it: this is generated into a
  // manifest, and a malformed name there fails at publish time with nothing
  // pointing back here.
  if (main.startsWith('@')) {
    throw new Error(`the main package is scoped (${main}); packageName() composes a scope from it and cannot`)
  }
  return `@${main}/${suffix}`
}

/**
 * The host key a running process derives for a target.
 *
 * Identical to the suffix, and that is the invariant `src/addon.ts` documents:
 * on Linux the key carries the C library, because one `platform-arch` has both
 * a glibc and a musl build and a key that could not say which would have two
 * answers. Written as a pass-through rather than dropped so the relation is
 * stated where it is relied upon.
 */
function hostKey(suffix) {
  return suffix
}

/** The `PLATFORM_PACKAGES` module, as source. */
function platformPackages(main) {
  const entries = Object.keys(TARGETS)
    .sort()
    .map(suffix => `  '${hostKey(suffix)}': '${packageName(main, suffix)}',`)
    .join('\n')

  return `// Generated by \`just platform-packages\` from \`TARGETS\` in
// \`tools/stage-platform-package.mjs\`. Do not edit: \`just ci\` regenerates this
// file and fails on a difference, so an edit here is a build failure rather
// than a change.
//
// It exists because \`src/addon.ts\` ships and \`tools/\` does not, so the
// runtime cannot import the list it needs. Adding a target is a row in
// \`TARGETS\` and a regenerate.

/**
 * The platform packages, keyed by the triple \`target()\` derives.
 *
 * **The key carries the C library on Linux.** One \`platform-arch\` has both a
 * glibc and a musl build, so a key that stopped at the architecture would have
 * two answers; carrying the libc keeps one answer per key, and makes these keys
 * exactly the suffixes a release builds.
 */
export const PLATFORM_PACKAGES: Readonly<Record<string, string>> = {
${entries}
}
`
}

/** `package.json`, with `optionalDependencies` rewritten from the same list. */
function manifest(current) {
  const optional = {}
  for (const suffix of Object.keys(TARGETS).sort()) {
    // An exact pin rather than a range, and the reason is the artefact: the
    // binary and the JavaScript that calls it are one thing cut at one commit,
    // and a range would let a package manager pair a new surface with an older
    // addon.
    optional[packageName(current.name, suffix)] = current.version
  }
  return { ...current, optionalDependencies: optional }
}

// An explicit destination lets the drift check emit somewhere disposable and
// diff the result, rather than asking git what changed — git's answer depends
// on whether a file is untracked, written or staged.
const out = process.argv[2]
const current = JSON.parse(readFileSync(PACKAGE, 'utf8'))

const generatedTo = out === undefined ? GENERATED : resolve(out, 'platform-packages.ts')
const manifestTo = out === undefined ? PACKAGE : resolve(out, 'package.json')

writeFileSync(generatedTo, platformPackages(current.name), 'utf8')
writeFileSync(manifestTo, `${JSON.stringify(manifest(current), null, 2)}\n`, 'utf8')

process.stderr.write(`platform packages: ${Object.keys(TARGETS).length}\n`)
