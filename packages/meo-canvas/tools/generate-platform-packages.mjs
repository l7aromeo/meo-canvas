// Writes the two places a target is named besides `TARGETS`: `optionalDependencies`
// in `package.json`, which an install fetches, and `PLATFORM_PACKAGES` in
// `src/generated/platform-packages.ts`, which a process resolves. Committed, since
// `src/addon.ts` ships and `tools/` does not; a gate fails on a difference.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { TARGETS, packageName } from './stage-platform-package.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const PACKAGE = resolve(HERE, '../package.json')
const GENERATED = resolve(HERE, '../src/generated/platform-packages.ts')

/**
 * The host key a running process derives for a target: the suffix itself, which
 * on Linux carries the C library. A pass-through, so the relation is stated where
 * it is relied upon.
 */
function hostKey(suffix) {
  return suffix
}

/** The `PLATFORM_PACKAGES` module, as source. */
function platformPackages(main) {
  const entries = Object.keys(TARGETS)
    .sort()
    .map(suffix => `  '${hostKey(suffix)}': '${packageName(main, suffix)}',`)
    .join('\n')

  return `// Generated by \`just platform-packages\` from \`TARGETS\` in
// \`tools/stage-platform-package.mjs\`; \`just ci\` fails on a difference, so do not
// edit. Committed because \`src/addon.ts\` ships and \`tools/\` does not; adding a
// target is a row in \`TARGETS\` and a regenerate.

/**
 * The platform packages, keyed by the triple \`target()\` derives. On Linux the key
 * carries the C library, since one \`platform-arch\` has a glibc and a musl build,
 * so the keys are exactly the suffixes a release builds.
 */
export const PLATFORM_PACKAGES: Readonly<Record<string, string>> = {
${entries}
}
`
}

/** `package.json`, with `optionalDependencies` rewritten from the same list. */
function manifest(current) {
  const optional = {}
  for (const suffix of Object.keys(TARGETS).sort()) {
    // An exact pin rather than a range, and the reason is the artefact: the
    // binary and the JavaScript that calls it are one thing cut at one commit,
    // and a range would let a package manager pair a new surface with an older
    // addon.
    optional[packageName(current.name, suffix)] = current.version
  }
  return { ...current, optionalDependencies: optional }
}

// An explicit destination lets the drift check emit somewhere disposable and
// diff the result, rather than asking git what changed — git's answer depends
// on whether a file is untracked, written or staged.
const out = process.argv[2]
const current = JSON.parse(readFileSync(PACKAGE, 'utf8'))

const generatedTo = out === undefined ? GENERATED : resolve(out, 'platform-packages.ts')
const manifestTo = out === undefined ? PACKAGE : resolve(out, 'package.json')

writeFileSync(generatedTo, platformPackages(current.name), 'utf8')
writeFileSync(manifestTo, `${JSON.stringify(manifest(current), null, 2)}\n`, 'utf8')

process.stderr.write(`platform packages: ${Object.keys(TARGETS).length}\n`)
