//! The animation helpers against v1's own numbers.
//!
//! # Why the comparison is exact
//!
//! Every value in `tests/assets/animate` was printed at JavaScript's default
//! precision, which is the shortest string that round-trips an `f64`. So both
//! surfaces parse the identical number and **there is no tolerance here at
//! all**: a difference of one bit is a difference. That is only affordable
//! because the module refuses fused multiply-add, which rounds once where
//! JavaScript rounds twice -- see `animate::easing`.
//!
//! If a row ever needs an epsilon, the epsilon is the finding.
//!
//! # What this table does not cover
//!
//! **Six hundred rows are a count, not a measure of how many things were
//! asked.** These four files exercise `easing` and `spring` and reach
//! `color`, `interpolate`, `track` and `sequence` **not at all** -- the
//! vectors are values of curves, and everything around the curves is
//! machinery no curve value can see. Those four are covered by unit tests
//! beside their own code. A reader who takes 612 rows as thoroughness will be
//! wrong about two thirds of the module.
//!
//! # Why v1 and not a derivation
//!
//! Generated by running v1's built module at tag `v9.0.2`, commit `890eed2`.
//! Deriving the table by hand would have made one reader's arithmetic the
//! referee for two implementations, which is the defect it exists to prevent,
//! one level up.

#![expect(
    clippy::float_cmp,
    reason = "the exact comparison IS the assertion. Both sides parse the \
              same shortest-round-trip decimal, so equality is the strongest \
              claim available and an epsilon here would hide the disagreement \
              this file exists to find. Where an epsilon is unavoidable it is \
              `EXP_ULP`, which is measured rather than chosen."
)]

use meo_canvas_core::animate::{
    easing::{Easing, cubic_bezier, steps},
    spring::Spring,
};

/// The rows of one vector file, comments dropped and fields split.
fn rows(text: &'static str) -> impl Iterator<Item = Vec<&'static str>> {
    text.lines()
        .filter(|line| !line.starts_with('#') && !line.trim().is_empty())
        .map(|line| line.split('\t').collect())
}

/// One field as the `f64` it round-trips to.
fn at(row: &[&str], index: usize) -> f64 {
    row[index]
        .parse()
        .unwrap_or_else(|error| unreachable!("{:?}: {error}", row[index]))
}

#[test]
fn every_curve_in_the_catalogue_matches_v1() {
    let table = include_str!("assets/animate/easing.tsv");
    let mut checked = 0;
    for row in rows(table) {
        let curve = Easing::ALL
            .into_iter()
            .find(|curve| curve.name() == row[0])
            .unwrap_or_else(|| {
                unreachable!("{} is not in the catalogue", row[0])
            });
        let (t, expected) = (at(&row, 1), at(&row, 2));
        let ours = curve.at(t);
        assert!(
            ours == expected,
            "{}({t}) is {ours} where v1 draws {expected}",
            row[0]
        );
        checked += 1;
    }
    // The catalogue and the table have to be the same size, or a curve we
    // never wrote would pass by not being asked about.
    assert_eq!(checked, 403, "the table changed size");
}

#[test]
fn the_catalogue_is_the_whole_catalogue() {
    let table = include_str!("assets/animate/easing.tsv");
    let named: std::collections::HashSet<&str> =
        rows(table).map(|row| row[0]).collect();
    for curve in Easing::ALL {
        assert!(named.contains(curve.name()), "{} is untested", curve.name());
    }
    assert_eq!(
        named.len(),
        Easing::ALL.len(),
        "a curve is missing from one side"
    );
}

#[test]
fn a_bezier_solves_where_v1_solves() {
    let table = include_str!("assets/animate/bezier.tsv");
    for row in rows(table) {
        let (x1, y1) = (at(&row, 0), at(&row, 1));
        let (x2, y2) = (at(&row, 2), at(&row, 3));
        let (t, expected) = (at(&row, 4), at(&row, 5));
        let ours = cubic_bezier(x1, y1, x2, y2)(t);
        assert!(
            ours == expected,
            "cubic-bezier({x1}, {y1}, {x2}, {y2}) at {t} is {ours} where v1 \
             gives {expected}"
        );
    }
}

#[test]
fn steps_land_on_the_side_v1_lands_on() {
    let table = include_str!("assets/animate/steps.tsv");
    for row in rows(table) {
        let count = row[0]
            .parse::<u32>()
            .unwrap_or_else(|error| unreachable!("{error}"));
        let (t, expected) = (at(&row, 1), at(&row, 2));
        let ours =
            steps(count).unwrap_or_else(|error| unreachable!("{error}"))(t);
        assert!(
            ours == expected,
            "steps({count}) at {t} is {ours} where v1 gives {expected}"
        );
    }
}

