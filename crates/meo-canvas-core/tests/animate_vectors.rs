/// How many representable `f64` values lie between two numbers.
fn ulps_between(ours: f64, theirs: f64) -> i64 {
    #[expect(
        clippy::cast_possible_wrap,
        reason = "both values are small positive-exponent finites here, so \
                  the bit patterns are far from the sign boundary"
    )]
    let bits = |value: f64| value.to_bits() as i64;
    (bits(ours) - bits(theirs)).abs()
}

/// The only tolerance in this file, and it is measured rather than chosen.
///
/// **`Math.exp` differs between V8 and Rust's libm by one ulp on some
/// arguments**, which no amount of writing the same arithmetic can close: a
/// transcendental function is not required to be correctly rounded and the two
/// runtimes round differently. Verified by comparing the bit patterns of the
/// intermediates directly, at `stiffness 100, damping 10, t 0.35`:
///
/// ```text
/// omega_d  4021520cd1372fea   identical -- sqrt is exact by IEEE 754
/// cos      bfefce08c8431e64   identical
/// sin      3fbc3b3e5006087c   identical
/// exp      3fc63e397e022073 against V8's ...072   one ulp apart
/// ```
///
/// So the bound is one ulp, and it applies to the spring alone: **every other
/// function in this file compares exactly**, because none of them reaches
/// `exp`. Two rows of the 77 differ, both by exactly one.
///
/// **Measured over the rows in this table, and not proven for any other.**
/// V8 and libm may differ by more at other arguments; one ulp is what these
/// ones produced. **Anyone adding a spring row re-verifies the bound rather
/// than assuming it** -- otherwise the number reads as a property of `exp`
/// when it is a property of these samples, and it would stay correct through
/// every row that happened to agree and fail silently at the first that did
/// not.
const EXP_ULP: i64 = 1;

#[test]
fn a_spring_settles_where_v1_settles() {
    let table = include_str!("assets/animate/spring.tsv");
    let mut regimes = (0, 0, 0);
    for row in rows(table) {
        let spring = Spring {
            from: at(&row, 0),
            to: at(&row, 1),
            stiffness: at(&row, 2),
            damping: at(&row, 3),
            mass: at(&row, 4),
            velocity: at(&row, 5),
        };
        let (t, expected) = (at(&row, 6), at(&row, 7));
        let ours = spring.at(t).unwrap_or_else(|error| unreachable!("{error}"));
        assert!(
            ulps_between(ours, expected) <= EXP_ULP,
            "a spring at {t}s is {ours} where v1 gives {expected}, which is \
             {} ulp apart (stiffness {}, damping {})",
            ulps_between(ours, expected),
            spring.stiffness,
            spring.damping
        );

        // Which regime each row exercised, so the table cannot quietly test
        // one solution three times.
        let zeta =
            spring.damping / (2.0 * (spring.stiffness * spring.mass).sqrt());
        if (zeta - 1.0).abs() < 1e-4 {
            regimes.1 += 1;
        } else if zeta < 1.0 {
            regimes.0 += 1;
        } else {
            regimes.2 += 1;
        }
    }
    // All three solutions are exercised, which a row count cannot tell you: a
    // table can hit one regime seventy-seven times and report coverage.
    // `stiffness 100, damping 20` gives a damping ratio of exactly 1 and is
    // what reaches the critical branch -- it was in the table before anyone
    // noticed it was the critical case, which is the argument for asserting
    // the regimes rather than assuming them.
    let (under, critical, over) = regimes;
    assert!(
        under > 0,
        "no underdamped row: the oscillating solution is untested"
    );
    assert!(
        critical > 0,
        "no critical row: the limiting solution is untested"
    );
    assert!(
        over > 0,
        "no overdamped row: the two-exponential solution is untested"
    );
}

#[test]
fn a_spring_without_an_equation_is_refused() {
    let none = Spring {
        stiffness: 0.0,
        ..Spring::default()
    };
    assert!(
        none.at(0.5).is_err(),
        "a spring with no stiffness has no equation"
    );
    assert!(
        Spring {
            damping: -1.0,
            ..Spring::default()
        }
        .at(0.5)
        .is_err()
    );
    assert!(
        Spring {
            mass: 0.0,
            ..Spring::default()
        }
        .at(0.5)
        .is_err()
    );
    assert!(Spring::default().at(0.5).is_ok());
}
